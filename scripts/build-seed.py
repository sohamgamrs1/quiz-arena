#!/usr/bin/env python3
"""Generate supabase/seed.sql from data/question-bank.json.

Seeds one demo auth user, one published quiz and the whole starter bank, so a fresh
`supabase db reset` gives you something to host immediately.
"""
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
BANK = ROOT / "data" / "question-bank.json"
OUT = ROOT / "supabase" / "seed.sql"

DEMO_UID = "00000000-0000-4000-8000-000000000001"
DEMO_EMAIL = "demo@quizarena.local"
DEMO_PASSWORD = "quizarena"


def q(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def main() -> None:
    bank = json.loads(BANK.read_text())
    quiz = bank["quiz"]
    questions = bank["questions"]

    lines = [
        "-- seed.sql — generated by scripts/build-seed.py, do not edit by hand.",
        f"-- Demo login: {DEMO_EMAIL} / {DEMO_PASSWORD}",
        "",
        "do $$",
        "declare",
        f"  v_uid uuid := {q(DEMO_UID)};",
        "  v_quiz_id uuid;",
        "  v_has_crypt boolean;",
        "begin",
        "  select exists (",
        "    select 1 from pg_proc p join pg_namespace n on n.oid = p.pronamespace",
        "    where n.nspname = 'extensions' and p.proname = 'crypt'",
        "  ) into v_has_crypt;",
        "",
        "  if not exists (select 1 from auth.users u where u.id = v_uid) then",
        "    insert into auth.users (",
        "      instance_id, id, aud, role, email, encrypted_password, email_confirmed_at,",
        "      created_at, updated_at, raw_app_meta_data, raw_user_meta_data, is_super_admin",
        "    ) values (",
        "      '00000000-0000-0000-0000-000000000000', v_uid, 'authenticated', 'authenticated',",
        f"      {q(DEMO_EMAIL)},",
        "      case when v_has_crypt",
        f"        then extensions.crypt({q(DEMO_PASSWORD)}, extensions.gen_salt('bf'))",
        "        else null end,",
        "      now(), now(), now(),",
        "      '{\"provider\":\"email\",\"providers\":[\"email\"]}'::jsonb,",
        f"      jsonb_build_object('display_name', 'demo host'),",
        "      false",
        "    );",
        "",
        "    insert into auth.identities (id, user_id, provider_id, identity_data, provider, last_sign_in_at, created_at, updated_at)",
        "    values (gen_random_uuid(), v_uid, v_uid::text,",
        f"      jsonb_build_object('sub', v_uid::text, 'email', {q(DEMO_EMAIL)}),",
        "      'email', now(), now(), now())",
        "    on conflict do nothing;",
        "  end if;",
        "",
        "  insert into public.profiles (id, display_name, avatar_emoji)",
        "  values (v_uid, 'demo host', '🎩')",
        "  on conflict (id) do nothing;",
        "",
        "  select id into v_quiz_id from public.quizzes",
        f"  where owner_id = v_uid and title = {q(quiz['title'])};",
        "",
        "  if v_quiz_id is null then",
        "    insert into public.quizzes (owner_id, title, description, cover_emoji, status)",
        "    values (",
        "      v_uid,",
        f"      {q(quiz['title'])},",
        f"      {q(quiz.get('description') or '')},",
        f"      {q(quiz.get('cover_emoji') or '🎯')},",
        "      'published'",
        "    )",
        "    returning id into v_quiz_id;",
        "  end if;",
        "",
        "  delete from public.questions q where q.quiz_id = v_quiz_id;",
        "",
        "  insert into public.questions",
        "    (quiz_id, position, prompt, options, correct_option_id, time_limit_ms, points_base, explanation)",
        "  values",
    ]

    rows = []
    for item in questions:
        options = json.dumps(item["options"], ensure_ascii=False)
        rows.append(
            "    (v_quiz_id, {pos}, {prompt}, {options}::jsonb, {correct}, {tl}, {pb}, {exp})".format(
                pos=item["position"],
                prompt=q(item["prompt"]),
                options=q(options),
                correct=q(item["correct_option_id"]),
                tl=item["time_limit_ms"],
                pb=item["points_base"],
                exp=q(item["explanation"] or ""),
            )
        )

    lines.append(",\n".join(rows) + ";")
    lines += ["end $$;", ""]

    OUT.write_text("\n".join(lines))
    print(f"wrote {OUT.relative_to(ROOT)}: 1 quiz, {len(questions)} questions")


if __name__ == "__main__":
    main()
